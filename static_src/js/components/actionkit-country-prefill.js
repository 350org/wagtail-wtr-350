class ActionKitCountryPrefill {
    static init() {
        const selects = document.querySelectorAll('.wtr-actionkit-embed select[name="country"]');
        if (!selects.length) { return; }

        fetch('/cdn-cgi/trace')
            .then((response) => response.text())
            .then((text) => {
                const match = text.match(/^loc=([A-Z]{2})$/m);
                if (!match) { return; }
                const countryName = COUNTRY_NAMES_BY_CODE[match[1]];
                if (!countryName) { return; }

                selects.forEach((select) => {
                    if (select.value) { return; }
                    const option = select.querySelector(`option[value="${CSS.escape(countryName)}"]`);
                    if (!option) { return; }
                    select.value = countryName;
                    select.dispatchEvent(new Event('change', { bubbles: true }));
                });
            })
            .catch(() => {});
    }
}

export default ActionKitCountryPrefill;
